export function structured(result) {
  if (result?.isError) {
    const code = result?.structuredContent?.code;
    const error = new Error(messages[code] || "这次操作没有完成，请稍后重试。");
    error.code = code;
    throw error;
  }
  if (!result?.structuredContent || typeof result.structuredContent !== "object") throw new Error("旅行服务返回的内容无法读取。");
  return result.structuredContent;
}
