import { createTravelCloudApp } from '../dsh/cloud-app.mjs';
import { loadTravelRuntimeEnv } from '../http/runtime-env.mjs';
const env=await loadTravelRuntimeEnv();
if(!env.DATABASE_URL)throw new Error('execution_worker_requires_postgres');
const cloud=await createTravelCloudApp({...env,TRAVEL_AGENT_EXECUTION_ROLE:'worker'});
await cloud.app.locals.executionService.repository.migrate();
cloud.app.locals.executionService.timer.ref();
process.stdout.write('DSH Travel worker ready.\n');
await new Promise(resolve=>{process.once('SIGTERM',resolve);process.once('SIGINT',resolve)});
await cloud.close();
